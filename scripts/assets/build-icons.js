// Sprite id -> Simple Icons name (CC0). Brand marks are filled, not stroked.
const BRANDS = { google: "google", github: "github", instagram: "instagram" };

// Neither package ships a LinkedIn mark any more, so it is drawn here.
const LINKEDIN = [
  '<symbol id="i-linkedin" viewBox="0 0 24 24"><path fill="currentColor" stroke="none" ',
  'd="M4 3h16a1 1 0 0 1 1 1v16a1 1 0 0 1-1 1H4a1 1 0 0 1-1-1V4a1 1 0 0 1 1-1Zm2.3 7.4V18h2.5v-7.6H6.3Zm1.25-3.8',
  "a1.45 1.45 0 1 0 0 2.9 1.45 1.45 0 0 0 0-2.9ZM10.6 10.4V18h2.5v-3.9c0-1.1.4-1.9 1.5-1.9s1.3.9 1.3 1.9V18h2.5",
  'v-4.5c0-2.2-1.2-3.3-3-3.3-1.2 0-2 .6-2.3 1.2v-1H10.6Z"/></symbol>',
].join("");

const symbols = [];

for (const [id, name] of Object.entries(LUCIDE)) {
  const svg = fs.readFileSync(path.join(modules, "lucide-static", "icons", `${name}.svg`), "utf8");
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/\s*\n\s*/g, "");
  symbols.push(`<symbol id="i-${id}" viewBox="0 0 24 24">${inner}</symbol>`);
}

for (const [id, name] of Object.entries(BRANDS)) {
  const svg = fs.readFileSync(path.join(modules, "simple-icons", "icons", `${name}.svg`), "utf8");
  const d = svg.match(/ d="([^"]+)"/)[1];
  symbols.push(
    `<symbol id="i-${id}" viewBox="0 0 24 24"><path fill="currentColor" stroke="none" d="${d}"/></symbol>`,
  );
}

symbols.push(LINKEDIN);

const header =
  "<!-- Icons: Lucide (ISC License), Simple Icons (CC0). Generated by scripts/assets/build-icons.js -->";
fs.writeFileSync(
  OUTPUT,
  `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">${header}${symbols.join("")}</svg>\n`,
);
console.log(`Wrote ${symbols.length} icons to ${path.relative(process.cwd(), OUTPUT)}`);
