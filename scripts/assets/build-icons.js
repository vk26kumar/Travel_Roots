"use strict";

/**
 * Rebuilds public/images/icons.svg, the SVG sprite used by helpers.icon().
 *
 * The icon packages are not project dependencies, so install them in any
 * scratch folder first and pass that folder's node_modules path:
 *
 *   mkdir icon-tools && cd icon-tools && npm init -y && npm install lucide-static simple-icons
 *   node scripts/assets/build-icons.js ../icon-tools/node_modules
 *
 * To add an icon, add an entry below (sprite id -> Lucide file name, see
 * https://lucide.dev/icons) and run the script again.
 */

const fs = require("fs");
const path = require("path");

const modules = process.argv[2];
if (!modules) {
  console.error("Usage: node scripts/assets/build-icons.js <path-to-node_modules>");
  process.exit(1);
}

